"""Excel export (Origin-ready 3-line header) and Origin embedded-Python script generation."""
from __future__ import annotations

import json

import numpy as np


def write_excel(path, curves, refs, results):
    import openpyxl
    from openpyxl.styles import Font

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Plot data"
    col = 1
    for c in curves:
        ws.cell(1, col, "2Theta"), ws.cell(2, col, "deg"), ws.cell(3, col, c["label"])
        ws.cell(1, col + 1, "Intensity"), ws.cell(2, col + 1, "a.u. (stacked)"), ws.cell(3, col + 1, c["label"])
        ws.cell(1, col + 2, "Intensity"), ws.cell(2, col + 2, "a.u. (processed)"), ws.cell(3, col + 2, c["label"])
        for i, (x, y, y0) in enumerate(zip(c["x"], c["y_plot"], c["y"])):
            ws.cell(4 + i, col, round(float(x), 5))
            ws.cell(4 + i, col + 1, round(float(y), 6))
            ws.cell(4 + i, col + 2, round(float(y0), 6))
        col += 3
    for r in refs:
        ws.cell(1, col, "2Theta"), ws.cell(2, col, "deg"), ws.cell(3, col, r.name + " (ref)")
        ws.cell(1, col + 1, "Intensity"), ws.cell(2, col + 1, "%"), ws.cell(3, col + 1, r.name)
        ws.cell(1, col + 2, "hkl"), ws.cell(2, col + 2, ""), ws.cell(3, col + 2, r.name)
        for i, (t, I, h) in enumerate(zip(r.two_theta, r.intensity, r.hkl)):
            ws.cell(4 + i, col, round(float(t), 4)), ws.cell(4 + i, col + 1, round(float(I), 2))
            ws.cell(4 + i, col + 2, h)
        col += 3

    ws = wb.create_sheet("Peaks")
    hdr = ["Sample", "2Theta (deg)", "d (A)", "Height", "Rel. I (%)", "FWHM (deg)", "Area",
           "Crystallite size (nm)", "Fit R2", "Assigned (hkl)", "Phase"]
    ws.append(hdr)
    for res in results:
        for p in res["peaks"]:
            ws.append([res["name"], round(p["center"], 4), round(p["d"], 4), round(p["height"], 2),
                       round(p.get("rel_intensity", np.nan), 1), round(p["fwhm"], 4),
                       None if not np.isfinite(p["area"]) else round(p["area"], 2),
                       None if not np.isfinite(p.get("size_nm", np.nan)) else round(p["size_nm"], 1),
                       None if not np.isfinite(p["r2"]) else round(p["r2"], 3),
                       p.get("hkl", ""), p.get("phase", "")])
    ws = wb.create_sheet("Phase match")
    ws.append(["Sample", "Reference", "Score (0-1)", "Median shift (deg)", "hkl", "Ref 2Theta",
               "Ref I", "Found", "Obs 2Theta", "Shift (deg)"])
    for res in results:
        for m in res["matches"]:
            for ln in m["lines"]:
                ws.append([res["name"], m["reference"], round(m["score"], 3),
                           None if not np.isfinite(m["median_shift"]) else round(m["median_shift"], 3),
                           ln["hkl"], round(ln["ref_2theta"], 3), round(ln["ref_I"], 1),
                           "yes" if ln["found"] else "no",
                           None if not ln["found"] else round(ln["obs_2theta"], 3),
                           None if not ln["found"] else round(ln["shift"], 3)])
    if any(res.get("texture") for res in results):
        ws = wb.create_sheet("Texture")
        ws.append(["Sample", "Reference", "hkl", "Obs 2Theta", "TC(hkl)"])
        for res in results:
            for refname, rows in res.get("texture", {}).items():
                for t in rows:
                    ws.append([res["name"], refname, t["hkl"], round(t["obs_2theta"], 3), round(t["TC"], 3)])
    if any(res.get("ratios") for res in results):
        ws = wb.create_sheet("Ratios")
        ws.append(["Sample", "Ratio", "Value", "Note"])
        for res in results:
            for r in res["ratios"]:
                ws.append([res["name"], r["label"], None if r["value"] is None else round(r["value"], 3), r["note"]])
    for w in wb.worksheets:
        for c in w[1]:
            c.font = Font(bold=True)
    wb.save(path)


