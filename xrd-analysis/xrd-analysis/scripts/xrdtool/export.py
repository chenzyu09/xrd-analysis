def lt_num(expr):
    """Read a LabTalk numeric expression (e.g. an object's width)."""
    try:
        gl.lt_exec(f"double __xrdv = {expr};")
        return float(op.lt_float("__xrdv"))
    except Exception:  # noqa: BLE001
        return None


def put_label(text, x_right, y_floor, hexcolor, size, xs=None, ys=None):
    """Text whose right edge sits at x_right and whose bottom sits just above the curve below it."""
    r, g, b = int(hexcolor[1:3], 16), int(hexcolor[3:5], 16), int(hexcolor[5:7], 16)
    try:
        lab = gl.add_label(text, x_right, y_floor)
        nm = lab.name
    except Exception as e:  # noqa: BLE001
        print("skip: label", text, e)
        return
    safe(lambda: gl.lt_exec(f"{nm}.fsize={size}; {nm}.font=font(Arial); {nm}.color=color({r},{g},{b});"),
         "label style")
    dx = lt_num(f"{nm}.dx")
    dy = lt_num(f"{nm}.dy")
    if dx is None or dy is None:
        return
    y_bottom = y_floor
    if xs is not None:
        seg = [y for x, y in zip(xs, ys) if x_right - dx <= x <= x_right and y == y]
        if seg:
            y_bottom = max(seg) + 0.03
    safe(lambda: gl.lt_exec(f"{nm}.x={x_right - dx / 2}; {nm}.y={y_bottom + dy / 2};"), "label position")


# fixed layer position on the page (percent of page) so stray objects cannot shrink the plot
safe(lambda: gl.lt_exec("layer.unit=1; layer.left=16; layer.top=5; layer.width=80; layer.height=75;"), "layer size")
x0, x1 = STYLE["x_range"]
xr = x1 - 0.015 * (x1 - x0)
lab_size = STYLE.get("label_size", int(fs * 0.6))
for r in DATA["refs"]:
    ys_ = [v for v in r["y"] if v == v]
    put_label(r["name"], xr, min(ys_) + 0.05, r["color"], lab_size)
for c in DATA["curves"]:
    put_label(c["label"], xr, c["label_y"], c["color"], lab_size, c["x"], c["y"])
print("XRD plot done.")
