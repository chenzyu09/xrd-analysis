def write_origin_script(path, curves, refs, cfg, y_top, ref_colors):
    data = {"curves": [], "refs": []}
    xmin, xmax = cfg["x_range"]
    for c in curves:
        m = (c["x"] >= xmin) & (c["x"] <= xmax)
        x = c["x"][m]
        y = c["y_plot"][m]
        stepn = max(1, len(x) // 6000)
        data["curves"].append({"x": [round(float(v), 4) for v in x[::stepn]],
                               "y": [round(float(v), 5) for v in y[::stepn]],
                               "label": c["label"], "color": c["color"],
                               "label_x": xmin + cfg["label_x"] * (xmax - xmin),
                               "label_y": float(c["label_y"])})
    for k, r in enumerate(refs):
        m = (r.two_theta >= xmin) & (r.two_theta <= xmax)
        base = -0.65 * (k + 1)
        xs, ys = [], []
        for t, I in zip(r.two_theta[m], r.intensity[m]):
            xs += [round(float(t), 4)] * 2 + [None]
            ys += [base, round(base + 0.55 * float(I) / 100, 4), None]
        data["refs"].append({"x": xs, "y": ys, "name": r.name,
                             "color": ref_colors[k % len(ref_colors)]})
    style = {"x_range": [xmin, xmax], "y_range": [-0.65 * len(refs) if refs else -0.05, y_top],
             "font_size": cfg["origin_font_size"], "frame_pt": cfg["origin_frame_pt"],
             "line_width_pt": cfg["origin_line_pt"]}
    txt = ORIGIN_TEMPLATE.replace("__DATA__", json.dumps(data, ensure_ascii=False)).replace(
        "__STYLE__", json.dumps(style))
    with open(path, "w", encoding="utf-8") as f:
        f.write(txt)
